const guidelineWidth = 375;

/**
 * Scales typography and other small visual measurements against the device
 * width while capping the result so tablets do not produce oversized UI.
 */
export const scale = (size: number) => {
  const widthScale = Dimensions.get('window').width / guidelineWidth;
  const responsiveSize = size + (size * widthScale - size) * 0.5;

  return PixelRatio.roundToNearestPixel(Math.min(responsiveSize, size * 1.2));
};

